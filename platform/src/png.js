const MAX_PNG_BYTES = 1_800_000;
const MAX_DIMENSION = 32_768;
const MAX_PIXELS = 64_000_000;
const schemaPromises = new WeakMap();
const encoder = new TextEncoder();
const signature = [137, 80, 78, 71, 13, 10, 26, 10];

export async function ensurePngSchema(env) {
  let promise = schemaPromises.get(env.DB);
  if (promise) return promise;
  promise = (async () => {
    await env.DB.prepare(`CREATE TABLE IF NOT EXISTS result_png_assets (
    result_id TEXT NOT NULL,
    position INTEGER NOT NULL,
    source_sha256 TEXT NOT NULL,
    png_sha256 TEXT NOT NULL,
    width INTEGER NOT NULL,
    height INTEGER NOT NULL,
    byte_length INTEGER NOT NULL,
    data BLOB NOT NULL,
    created_at TEXT NOT NULL DEFAULT (datetime('now')),
    PRIMARY KEY(result_id, position),
    FOREIGN KEY(result_id, position) REFERENCES result_assets(result_id, position) ON DELETE CASCADE
    )`).run();
    await env.DB.prepare(`CREATE TABLE IF NOT EXISTS result_png_previews (
      result_id TEXT PRIMARY KEY,
      png_sha256 TEXT NOT NULL,
      width INTEGER NOT NULL,
      height INTEGER NOT NULL,
      byte_length INTEGER NOT NULL,
      data BLOB NOT NULL,
      created_at TEXT NOT NULL DEFAULT (datetime('now')),
      FOREIGN KEY(result_id) REFERENCES results(id) ON DELETE CASCADE
    )`).run();
  })();
  schemaPromises.set(env.DB, promise);
  try {
    await promise;
  } catch (error) {
    if (schemaPromises.get(env.DB) === promise) schemaPromises.delete(env.DB);
    throw error;
  }
}

function chunkType(bytes, offset) {
  return String.fromCharCode(...bytes.subarray(offset, offset + 4));
}

// Rasters are generated by the runner or an authenticated offline backfill.
// The Worker validates and serves their bytes, avoiding request-time SVG
// rasterization and its CPU/font requirements on the free Workers plan.
export function parsePng(input) {
  let bytes;
  if (input instanceof Uint8Array) {
    bytes = input;
  } else if (input instanceof ArrayBuffer) {
    bytes = new Uint8Array(input);
  } else if (typeof input === "string") {
    const base64 = input.startsWith("data:image/png;base64,") ? input.slice(22) : input;
    if (!base64 || base64.length > Math.ceil(MAX_PNG_BYTES / 3) * 4 || base64.length % 4 !== 0 || !/^[A-Za-z0-9+/]*={0,2}$/.test(base64)) {
      throw new TypeError("Invalid PNG encoding");
    }
    try {
      if (typeof Uint8Array.fromBase64 === "function") bytes = Uint8Array.fromBase64(base64);
      else {
        const binary = atob(base64);
        bytes = new Uint8Array(binary.length);
        for (let index = 0; index < binary.length; index++) bytes[index] = binary.charCodeAt(index);
      }
    } catch {
      throw new TypeError("Invalid PNG encoding");
    }
  } else {
    throw new TypeError("Expected PNG bytes or base64");
  }

  if (bytes.byteLength < 45 || bytes.byteLength > MAX_PNG_BYTES || !signature.every((byte, index) => bytes[index] === byte)) {
    throw new TypeError("Invalid PNG file");
  }
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  if (view.getUint32(8) !== 13 || chunkType(bytes, 12) !== "IHDR") throw new TypeError("Invalid PNG header");
  const width = view.getUint32(16);
  const height = view.getUint32(20);
  if (!width || !height || width > MAX_DIMENSION || height > MAX_DIMENSION || width * height > MAX_PIXELS) {
    throw new TypeError("PNG dimensions are too large");
  }
  let offset = 8;
  let hasPixels = false;
  let complete = false;
  while (offset + 12 <= bytes.byteLength) {
    const length = view.getUint32(offset);
    const type = chunkType(bytes, offset + 4);
    const next = offset + 12 + length;
    if (next > bytes.byteLength) throw new TypeError("Truncated PNG chunk");
    if (type === "IDAT" && length > 0) hasPixels = true;
    if (type === "IEND") {
      complete = length === 0 && next === bytes.byteLength;
      break;
    }
    offset = next;
  }
  if (!complete || !hasPixels) throw new TypeError("Incomplete PNG file");
  return { bytes, width, height };
}

async function sha256(bytes) {
  const digest = new Uint8Array(await crypto.subtle.digest("SHA-256", bytes));
  return Array.from(digest, (byte) => byte.toString(16).padStart(2, "0")).join("");
}

export async function prepareReportPng(env, id, position, svg, input, options = {}) {
  if (!/^\d{8}$/.test(String(id)) || !Number.isInteger(Number(position)) || Number(position) < 1 || Number(position) > 8 || typeof svg !== "string") {
    throw new TypeError("Invalid report asset");
  }
  const { bytes, width, height } = parsePng(input);
  const [sourceHash, pngHash] = await Promise.all([sha256(encoder.encode(svg)), sha256(bytes)]);
  await ensurePngSchema(env);
  // Compare the exact SVG as well as its ID. A backfill for an older source
  // must not attach a raster to another asset after concurrent moderation.
  const tokenGuard = options.tokenHash ? " AND EXISTS (SELECT 1 FROM secure_upload_tokens WHERE result_id=? AND token_hash=? AND expires_at>datetime('now') AND uploaded_count<expected_count)" : "";
  const values = [String(id), Number(position), sourceHash, pngHash, width, height, bytes.byteLength,
    bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), String(id), Number(position), svg];
  if (options.tokenHash) values.push(String(id), options.tokenHash);
  const statement = env.DB.prepare(`INSERT INTO result_png_assets(result_id,position,source_sha256,png_sha256,width,height,byte_length,data)
    SELECT ?,?,?,?,?,?,?,? FROM result_assets
    WHERE result_id=? AND position=? AND mime='image/svg+xml' AND data=?${tokenGuard}
    ON CONFLICT(result_id,position) DO NOTHING`)
    .bind(...values);
  return { statement, sourceHash, pngHash, width, height, byte_length: bytes.byteLength };
}

export async function storeReportPng(env, id, position, svg, input) {
  const prepared = await prepareReportPng(env, id, position, svg, input);
  const inserted = await prepared.statement.run();
  if (!inserted.meta?.changes) {
    const existing = await env.DB.prepare("SELECT source_sha256,png_sha256 FROM result_png_assets WHERE result_id=? AND position=?")
      .bind(String(id), Number(position)).first();
    if (existing?.source_sha256 === prepared.sourceHash && existing.png_sha256 === prepared.pngHash) {
      return { stored: true, created: false, width: prepared.width, height: prepared.height, byte_length: prepared.byte_length };
    }
    throw new Error("PNG source is missing, changed, or already immutable");
  }
  return { stored: true, created: true, width: prepared.width, height: prepared.height, byte_length: prepared.byte_length };
}

export async function preparePreviewPng(env, id, input, options = {}) {
  if (!/^\d{8}$/.test(String(id))) throw new TypeError("Invalid report ID");
  const { bytes, width, height } = parsePng(input);
  if (width !== 1200 || height !== 630) throw new TypeError("A report preview must be 1200 × 630 pixels");
  const pngHash = await sha256(bytes);
  await ensurePngSchema(env);
  const tokenGuard = options.tokenHash ? " AND EXISTS (SELECT 1 FROM secure_upload_tokens WHERE result_id=? AND token_hash=? AND expires_at>datetime('now') AND uploaded_count<expected_count)" : "";
  const values = [String(id), pngHash, width, height, bytes.byteLength,
    bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), String(id)];
  if (options.tokenHash) values.push(String(id), options.tokenHash);
  const statement = env.DB.prepare(`INSERT INTO result_png_previews(result_id,png_sha256,width,height,byte_length,data)
    SELECT ?,?,?,?,?,? FROM results WHERE id=?${tokenGuard} ON CONFLICT(result_id) DO NOTHING`).bind(...values);
  return { statement, pngHash, width, height, byte_length: bytes.byteLength };
}

export async function storePreviewPng(env, id, input) {
  const prepared = await preparePreviewPng(env, id, input);
  const inserted = await prepared.statement.run();
  if (!inserted.meta?.changes) {
    const existing = await env.DB.prepare("SELECT png_sha256 FROM result_png_previews WHERE result_id=?").bind(String(id)).first();
    if (existing?.png_sha256 !== prepared.pngHash) throw new Error("PNG preview is missing or already immutable");
  }
  return { stored: true, created: Boolean(inserted.meta?.changes), width: prepared.width, height: prepared.height, byte_length: prepared.byte_length };
}

export async function listReportPngs(env, id) {
  await ensurePngSchema(env);
  const rows = await env.DB.prepare("SELECT position,width,height,byte_length FROM result_png_assets WHERE result_id=? ORDER BY position")
    .bind(String(id)).all();
  return rows.results || [];
}

function missingImage(request) {
  return new Response(request.method === "HEAD" ? null : "PNG not found", { status: 404, headers: { "cache-control": "no-store" } });
}

function etagMatches(request, etag) {
  return (request.headers.get("if-none-match") || "").split(",").some((value) => value.trim() === "*" || value.trim().replace(/^W\//, "") === etag);
}

async function imageResponse(request, env, ctx, metadata, dataStatement) {
  const url = new URL(request.url);
  const headers = {
    "content-type": "image/png",
    "content-length": String(metadata.byte_length),
    "cache-control": "public, max-age=31536000, immutable",
    "x-content-type-options": "nosniff",
    "content-security-policy": "default-src 'none'; sandbox",
    etag: '"' + metadata.png_sha256 + '"',
  };
  if (etagMatches(request, headers.etag)) return new Response(null, { status: 304, headers });
  if (request.method === "HEAD") return new Response(null, { headers });
  const canonicalOrigin = new URL(env.PUBLIC_ORIGIN || url.origin).origin;
  const key = new Request(new URL(url.pathname, canonicalOrigin));
  const cache = globalThis.caches?.default;
  if (cache) {
    try {
      const cached = await cache.match(key);
      if (cached) return cached;
    } catch {
      // The durable PNG in D1 remains available during cache failures.
    }
  }
  const row = await dataStatement.first();
  if (!row) return missingImage(request);
  // D1 returns BLOB values as number arrays, while local SQLite adapters may
  // return Uint8Array. Both must become binary response bytes, never CSV text.
  const response = new Response(new Uint8Array(row.data), { headers });
  if (cache) {
    const write = cache.put(key, response.clone()).catch(() => {});
    if (ctx?.waitUntil) ctx.waitUntil(write);
    else await write;
  }
  return response;
}

export async function pngImageResponse(request, env, ctx) {
  const url = new URL(request.url);
  const match = url.pathname.match(/^\/assets\/(\d{8})\/([1-8])\.png$/);
  if (!match || !["GET", "HEAD"].includes(request.method)) return null;
  await ensurePngSchema(env);
  const metadata = await env.DB.prepare(`SELECT p.png_sha256,p.width,p.height,p.byte_length
    FROM result_png_assets p JOIN result_assets a ON a.result_id=p.result_id AND a.position=p.position
    WHERE p.result_id=? AND p.position=?`).bind(match[1], Number(match[2])).first();
  if (!metadata) return missingImage(request);
  return imageResponse(request, env, ctx, metadata, env.DB.prepare("SELECT data FROM result_png_assets WHERE result_id=? AND position=? AND png_sha256=?")
    .bind(match[1], Number(match[2]), metadata.png_sha256));
}

export async function previewImageResponse(request, env, ctx) {
  const url = new URL(request.url);
  const match = url.pathname.match(/^\/test\/(\d{8})\/preview\.png$/);
  if (!match || !["GET", "HEAD"].includes(request.method)) return null;
  await ensurePngSchema(env);
  const metadata = await env.DB.prepare(`SELECT p.png_sha256,p.width,p.height,p.byte_length
    FROM result_png_previews p JOIN results r ON r.id=p.result_id WHERE p.result_id=?`).bind(match[1]).first();
  if (metadata) {
    return imageResponse(request, env, ctx, metadata, env.DB.prepare("SELECT data FROM result_png_previews WHERE result_id=? AND png_sha256=?")
      .bind(match[1], metadata.png_sha256));
  }
  const result = await env.DB.prepare("SELECT id FROM results WHERE id=?").bind(match[1]).first();
  if (!result) return missingImage(request);
  // A generic site card stays available while a legacy report is backfilled.
  // Do not cache this redirect: its dedicated 1200×630 card may arrive next.
  return new Response(null, { status: 307, headers: { location: "/preview.png", "cache-control": "no-store" } });
}
